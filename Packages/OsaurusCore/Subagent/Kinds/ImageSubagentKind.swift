//
//  ImageSubagentKind.swift
//  OsaurusCore — Subagent framework
//
//  The `image` kind (upstream `ImageSubagentKind`), cloud branch only
//  (W-subagents stage 6, W-media-generation). It serves the single `image`
//  tool through the shared host (`SubagentSession`): the live feed row with
//  Stop, the recursion guard, telemetry and the compact result.
//
//  What runs on Intel: generation with an Osaurus Cloud or Venice image
//  model, through `MediaGenerationCoordinator` (upstream's cloud branch).
//  What does not (Incompatible, needs Apple Silicon): upstream's local MLX
//  branch (`NativeImageJobCoordinator`, residency handoff, step/ETA job
//  progress, image editing from `source_paths`, batches, samplers, adapters).
//  `ImageTool` has no such arguments on Intel.
//
//  Spend gates (unchanged from Intel's tool before the kind): the agent's
//  image switch, an explicit or configured model that must still exist
//  (never another billable model), the agent's Deny, and a billing approval
//  card before every image. Unlike upstream's local branch there is no
//  `autoApproveToolPrompts` and no Always Allow: a remote image always asks.
//

import Foundation

/// Parsed, validated `image` tool arguments (cloud generation).
struct ImageJobParams: Sendable {
    var prompt: String
    var model: String?
    var negativePrompt: String?
    var width: Int?
    var height: Int?
    var steps: Int?
    var guidance: Double?
    var seed: Int?
}

final class ImageSubagentKind: SubagentKind, @unchecked Sendable {
    let capability = SubagentCapabilityRegistry.image

    private let params: ImageJobParams
    private let argumentsJSON: String
    private let chatSessionId: String?
    private let services: IntelMediaKindServices
    private var selectedModel: MediaModelInfo?

    /// `chatSessionId` is the chat the tool call came from, read before the
    /// host binds its scope; nil outside a chat (no artifact card then).
    init(
        params: ImageJobParams,
        argumentsJSON: String,
        chatSessionId: String? = ChatExecutionContext.currentSessionId,
        services: IntelMediaKindServices = .live
    ) {
        self.params = params
        self.argumentsJSON = argumentsJSON
        self.chatSessionId = chatSessionId
        self.services = services
    }

    var feedTitle: String {
        let trimmed = params.prompt.trimmingCharacters(in: .whitespacesAndNewlines)
        let body = trimmed.count > 72 ? String(trimmed.prefix(72)) + "…" : trimmed
        return body.isEmpty ? "image" : "image: \(body)"
    }

    // MARK: - Model resolution (before any spend)

    func resolveModel(_ scope: SubagentScope) async throws -> ResolvedModel {
        let agent = await services.agentSettings(scope.agentId, true, false)
        guard agent.enabled else {
            throw SubagentError.unavailable(
                "Image generation is not enabled for this agent (Agents → Abilities → Images & Video)."
            )
        }
        let candidates = await services.imageCandidates()
        guard
            let model = IntelMediaToolSupport.resolve(
                requested: params.model, configured: agent.target, candidates: candidates)
        else {
            throw SubagentError.unavailable(
                params.model == nil
                    ? "No image generation model is available. Connect a Venice provider or sign in to Osaurus Cloud."
                    : "No configured image model matches '\(params.model ?? "")'."
            )
        }
        // Local models are MLX: not on Intel (upstream's local branch).
        guard model.target.backend != .local else {
            throw SubagentError.unavailable(MediaGenerationCoordinator.intelLocalUnsupported)
        }
        selectedModel = model
        return ResolvedModel(name: model.displayName, id: model.id, isLocal: false)
    }

    // MARK: - Permission

    func permission(_ scope: SubagentScope, _ resolved: ResolvedModel) async -> SubagentDecision {
        guard let model = selectedModel else {
            return .denied("The selected image model is no longer available.")
        }
        let agent = await services.agentSettings(scope.agentId, true, false)
        // Upstream: a remote image is billable, so it always asks unless the
        // agent's policy is Deny.
        guard agent.permission != .deny else {
            return .denied("Remote image generation is denied by this agent's permission settings.")
        }
        var approvalValues: [String: Any] = [
            "resolved_model": model.displayName,
            "backend": IntelMediaToolSupport.backendDescription(model),
            "billing_notice": "This image is generated by a billable remote provider.",
        ]
        if let privacy = model.privacy { approvalValues["privacy"] = privacy }
        if let minimum = model.pricing?.minimumUSD { approvalValues["estimated_minimum_usd"] = minimum }
        let approved = await services.requestApproval(
            "image",
            "Generate a billable remote image. The provider, privacy policy, and estimated "
                + "minimum price are shown in this approval.",
            SubagentApprovalArguments.enrichedJSON(from: argumentsJSON, values: approvalValues)
        )
        return approved ? .allow : .userDenied("User denied billable remote image generation.")
    }

    // MARK: - Run

    func run(
        _ scope: SubagentScope,
        _ resolved: ResolvedModel,
        feed: SubagentFeed,
        interrupt: InterruptToken
    ) async throws -> SubagentResult {
        guard let model = selectedModel else {
            throw SubagentError.executionFailed(
                message: "The image model expired before execution.", retryable: true)
        }
        feed.emitPhase("generating", detail: resolved.name)

        // Upstream's remote request: catalog sizes win over pixel sizes, and
        // one image per call (the transcript shows one artifact per call;
        // never bill for hidden variants).
        let constraints = model.constraints
        let usesPixelDimensions = constraints.aspectRatios.isEmpty && constraints.resolutions.isEmpty
        let request = MediaImageGenerationRequest(
            target: model.target,
            prompt: params.prompt,
            negativePrompt: params.negativePrompt,
            width: usesPixelDimensions ? params.width.map(IntelMediaToolSupport.clampedDimension) : nil,
            height: usesPixelDimensions ? params.height.map(IntelMediaToolSupport.clampedDimension) : nil,
            aspectRatio: constraints.defaultAspectRatio ?? constraints.aspectRatios.first,
            resolution: constraints.defaultResolution ?? constraints.resolutions.first,
            quality: constraints.defaultQuality ?? constraints.qualities.first,
            steps: params.steps.map { min(50, max(1, $0)) },
            guidance: params.guidance.map { min(20, max(0, $0)) },
            seed: params.seed.flatMap { $0 >= 0 ? $0 : nil },
            count: 1,
            format: .png
        )
        let generate = services.generateImage
        let generated: [GeneratedMedia]
        do {
            generated = try await IntelMediaToolSupport.cancellingOnInterrupt(interrupt) {
                try await generate(request)
            }
        } catch is CancellationError {
            if interrupt.isInterrupted { throw SubagentError.userDenied("User cancelled image generation.") }
            throw CancellationError()
        } catch let error as MediaGenerationError {
            throw SubagentError.executionFailed(
                message: error.localizedDescription, retryable: Self.isRetryable(error))
        } catch {
            throw SubagentError.executionFailed(message: error.localizedDescription, retryable: false)
        }
        guard let first = generated.first else {
            throw SubagentError.executionFailed(
                message: MediaGenerationError.invalidResponse.localizedDescription, retryable: false)
        }
        var payload: [String: Any] = [
            "kind": "generated_media_job",
            "media_type": "image",
            "mode": "generate",
            "job_id": first.url.deletingPathExtension().lastPathComponent,
            "model": first.modelID,
            "status": "completed",
            "already_displayed": true,
            "display_note": "The image is already shown to the user; do NOT call share_artifact for it.",
            "images": generated.map { ["path": $0.url.path, "url": $0.url.absoluteString] },
        ]
        if let settledCostUSD = first.settledCostUSD {
            payload["settled_cost_usd"] = settledCostUSD
        }
        if let card = await services.promote(
            first, "Image generation result from \(model.displayName)", chatSessionId)
        {
            payload["text"] = card
        }
        return SubagentResult(payload: payload, summary: "Generated 1 image with \(resolved.name).")
    }

    private static func isRetryable(_ error: MediaGenerationError) -> Bool {
        switch error {
        case .transport, .queuedJobContinues: return true
        default: return false
        }
    }
}
