//
//  IntelImageTool.swift
//  osaurus
//
//  Intel's `image` tool (`W-media-generation`). Upstream's `ImageTool`
//  (NativeImageTools.swift) generates or edits with local MLX bundles and
//  with cloud models through `ImageSubagentKind`; Intel has only the cloud
//  branch, so this tool generates (no editing: remote editing is not
//  supported upstream either) with the agent's Osaurus Cloud or Venice image
//  model. Upstream's generation-only schema minus the local controls
//  (sampler, adapters, batches, previews), which upstream rejects for remote
//  models anyway.
//

import Foundation

final class ImageTool: OsaurusTool, @unchecked Sendable {
    let name = "image"

    static let toolDescription =
        "Create an image with the user's configured image model: call with a `prompt`. The result is "
        + "shown to the user automatically; do NOT call share_artifact on it."

    var description: String { Self.toolDescription }
    var bypassRegistryTimeout: Bool { true }

    let parameters: JSONValue? = .object([
        "type": .string("object"),
        "additionalProperties": .bool(false),
        "properties": .object([
            "prompt": .object([
                "type": .string("string"),
                "description": .string("What to create."),
            ]),
            "model": .object([
                "type": .string("string"),
                "description": .string("Optional configured image model id. Omit to use the default."),
            ]),
            "negative_prompt": .object([
                "type": .string("string"),
                "description": .string("Optional negative prompt."),
            ]),
            "width": .object(["type": .string("integer"), "description": .string("Optional width in pixels.")]),
            "height": .object(["type": .string("integer"), "description": .string("Optional height in pixels.")]),
            "steps": .object(["type": .string("integer"), "description": .string("Optional denoise step count.")]),
            "guidance": .object(["type": .string("number"), "description": .string("Optional guidance scale.")]),
            "seed": .object(["type": .string("integer"), "description": .string("Optional deterministic seed.")]),
        ]),
        "required": .array([.string("prompt")]),
    ])

    init() {}

    func execute(argumentsJSON: String) async throws -> String {
        let argsReq = requireArgumentsDictionary(argumentsJSON, tool: name)
        guard case .value(let args) = argsReq else { return argsReq.failureEnvelope ?? "" }
        let promptReq = requireString(args, "prompt", expected: "non-empty image prompt", tool: name)
        guard case .value(let prompt) = promptReq else { return promptReq.failureEnvelope ?? "" }

        let agent = await IntelMediaToolSupport.agentSettings(forImage: true)
        guard agent.enabled else {
            return ToolEnvelope.failure(
                kind: .unavailable,
                message: "Image generation is not enabled for this agent (Agents → Abilities → Images & Video).",
                tool: name)
        }
        let candidates = await IntelMediaToolSupport.pickerItems()
            .imageGenerationDelegateCandidates.compactMap(\.mediaModel)
        let requested = IntelMediaToolSupport.optionalString(args["model"])
        guard
            let model = IntelMediaToolSupport.resolve(
                requested: requested, configured: agent.target, candidates: candidates)
        else {
            return ToolEnvelope.failure(
                kind: .unavailable,
                message: requested == nil
                    ? "No image generation model is available. Connect a Venice provider or sign in to Osaurus Cloud."
                    : "No configured image model matches '\(requested!)'.",
                tool: name)
        }

        // Upstream: a remote image is billable, so it always asks unless the
        // agent's policy is Deny.
        guard agent.permission != .deny else {
            return ToolEnvelope.failure(
                kind: .rejected,
                message: "Remote image generation is denied by this agent's permission settings.",
                tool: name)
        }
        var approvalValues: [String: Any] = [
            "resolved_model": model.displayName,
            "backend": IntelMediaToolSupport.backendDescription(model),
            "billing_notice": "This image is generated by a billable remote provider.",
        ]
        if let privacy = model.privacy { approvalValues["privacy"] = privacy }
        if let minimum = model.pricing?.minimumUSD { approvalValues["estimated_minimum_usd"] = minimum }
        let approved = await ToolPermissionPromptService.requestApproval(
            toolName: name,
            description:
                "Generate a billable remote image. The provider, privacy policy, and estimated "
                + "minimum price are shown in this approval.",
            argumentsJSON: SubagentApprovalArguments.enrichedJSON(from: argumentsJSON, values: approvalValues)
        )
        guard approved else {
            return ToolEnvelope.failure(
                kind: .userDenied, message: "User denied billable remote image generation.", tool: name)
        }

        // Upstream's remote request: catalog sizes win over pixel sizes, and
        // one image per call (the transcript shows one artifact per call;
        // never bill for hidden variants).
        let constraints = model.constraints
        let usesPixelDimensions = constraints.aspectRatios.isEmpty && constraints.resolutions.isEmpty
        let request = MediaImageGenerationRequest(
            target: model.target,
            prompt: prompt,
            negativePrompt: IntelMediaToolSupport.optionalString(args["negative_prompt"]),
            width: usesPixelDimensions
                ? ArgumentCoercion.int(args["width"]).map(IntelMediaToolSupport.clampedDimension) : nil,
            height: usesPixelDimensions
                ? ArgumentCoercion.int(args["height"]).map(IntelMediaToolSupport.clampedDimension) : nil,
            aspectRatio: constraints.defaultAspectRatio ?? constraints.aspectRatios.first,
            resolution: constraints.defaultResolution ?? constraints.resolutions.first,
            quality: constraints.defaultQuality ?? constraints.qualities.first,
            steps: ArgumentCoercion.int(args["steps"]).map { min(50, max(1, $0)) },
            guidance: IntelMediaToolSupport.optionalDouble(args["guidance"]).map { min(20, max(0, $0)) },
            seed: ArgumentCoercion.int(args["seed"]).flatMap { $0 >= 0 ? $0 : nil },
            count: 1,
            format: .png
        )
        let generated: [GeneratedMedia]
        do {
            generated = try await MediaGenerationCoordinator.shared.generateImage(request)
        } catch {
            return IntelMediaToolSupport.failure(error, tool: name)
        }
        guard let first = generated.first else {
            return IntelMediaToolSupport.failure(MediaGenerationError.invalidResponse, tool: name)
        }
        var payload: [String: Any] = [
            "kind": "generated_media_job",
            "media_type": "image",
            "mode": "generate",
            "job_id": first.url.deletingPathExtension().lastPathComponent,
            "model": first.modelID,
            "status": "completed",
            "already_displayed": true,
            "display_note": "The image is already shown to the user; do NOT call share_artifact for it.",
            "images": generated.map { ["path": $0.url.path, "url": $0.url.absoluteString] },
        ]
        if let settledCostUSD = first.settledCostUSD {
            payload["settled_cost_usd"] = settledCostUSD
        }
        if let card = await IntelMediaToolSupport.promoteToChatArtifact(
            first, description: "Image generation result from \(model.displayName)")
        {
            payload["text"] = card
        }
        return ToolEnvelope.success(tool: name, result: payload)
    }
}
